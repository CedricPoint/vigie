export const languages = { en: 'English', fr: 'Français' };

export function t(lang, key, vars = {}) {
  const text = dictionaries[lang]?.[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
